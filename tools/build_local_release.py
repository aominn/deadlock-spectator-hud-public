"""Build an asset-free package using an already verified runtime bundle.

Game images/native UI/MOD files are generated by setup, never copied into this ZIP.
"""
from pathlib import Path
import argparse,json,hashlib,shutil,sys,zipfile

def sha(f):
 h=hashlib.sha256()
 with f.open('rb') as stream:
  for part in iter(lambda:stream.read(2*1024**2),b''):h.update(part)
 return h.hexdigest()

def copy_files(source,target,skip=lambda name:False):
 for f in sorted(source.rglob('*')):
  if not f.is_file() or '__pycache__' in f.parts or f.suffix in ('.pyc','.pyo'):continue
  name=f.relative_to(source).as_posix()
  if skip(name):continue
  out=target/name;out.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(f,out)

def runtime_sources(root):
 # Read current source, never an older bundle's file list. Generated assets stay out.
 names=[]
 for folder,suffixes in [('engine',{'.py','.json','.ttf'}),('parser',{'.mjs','.json'})]:
  for f in sorted((root/folder).rglob('*')):
   rel=f.relative_to(root);parts=rel.parts
   if any(n in parts for n in ('__pycache__','node_modules','icons')) or f.suffix in ('.pyc','.pyo'):continue
   if not f.is_file():continue
   if f.is_symlink() or f.suffix not in suffixes:raise ValueError('Unexpected runtime source: '+rel.as_posix())
   if rel.as_posix()!='engine/effect-catalog.json':names.append(rel.as_posix())
 return names

def verify_notices(root):
 root=Path(root)
 for name in ['LICENSE','THIRD_PARTY_NOTICES.txt','licenses/THIRD-PARTY-INDEX.json']:
  if not (root/name).is_file():raise ValueError('Missing distribution notice: '+name)
 index=json.loads((root/'licenses/THIRD-PARTY-INDEX.json').read_text(encoding='utf-8'))
 if index.get('schema')!=1 or not index.get('components'):raise ValueError('Invalid distribution notice index')
 notices=index['notice_sha256']
 for component in index['components']:
  if not component.get('notice_files') or any(n not in notices for n in component['notice_files']):raise ValueError('Unindexed component notice')
 for name,expected in notices.items():
  f=root/name
  if not f.is_file() or sha(f)!=expected:raise ValueError('Distribution notice changed or missing: '+name)
 font=index['font'];f=root/font['file']
 if not f.is_file() or sha(f)!=font['sha256']:raise ValueError('Font does not match reviewed notice')
 return index

